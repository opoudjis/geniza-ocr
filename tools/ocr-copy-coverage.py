#!/usr/bin/env python3
"""ocr-copy-coverage.py — two copies of one work: which pages of each have a counterpart in the other.

    python3 tools/ocr-copy-coverage.py --a <text>... --b <text>... --out <new .tsv>

WHY (2026-10-10, the editor asked, of La Belga Sonorilo's two copies, the ÖNB bound volumes and the per-issue run, whether
there was a completeness issue with the two runs, and required that it be checked carefully; before one copy is retired). Page totals by
year cannot settle it (the bindings are two-year volumes); only the pages' own text can.

WHAT. Each input is an OCR text with «=== page N ===» markers (a search text, or a per-issue text). Every page is folded
(lower case, letters only) into five-word runs; a page of A is matched to the page of B sharing most of its runs, and the
other way round. A page with fewer than MIN_RUNS runs (a picture, a cover, a blank) is «too little text» and decided by
nothing here. A page whose best match shares under WEAK of its runs is «unmatched»: a lead for a look, never a finding of
a missing page by itself (OCR noise and advertisements also do it).

WRITE-SET: --out only (refuses an existing file); a one-line summary to the console.
"""
import argparse, collections, os, re, sys

MIN_RUNS, WEAK, K = 20, 0.10, 5
PAGE = re.compile(r"^=== page (\d+) ===\s*$", re.M)


def pages(path):
    t = open(path, encoding="utf-8", errors="ignore").read()
    parts = PAGE.split(t)
    item = os.path.splitext(os.path.basename(path))[0]
    for i in range(1, len(parts) - 1, 2):
        w = re.findall(r"[a-zà-öø-ÿĉĝĥĵŝŭ]+", parts[i + 1].lower())
        w = [x for x in w if len(x) > 1]
        yield (item, int(parts[i])), {" ".join(w[j:j + K]) for j in range(len(w) - K + 1)}


def side(paths):
    return dict(p for f in paths for p in pages(f))


def best(src, dst):
    idx = collections.defaultdict(set)
    for k, runs in dst.items():
        for r in runs:
            idx[r].add(k)
    out = {}
    for k, runs in src.items():
        if len(runs) < MIN_RUNS:
            out[k] = ("too little text", None, 0, len(runs))
            continue
        c = collections.Counter(d for r in runs for d in idx.get(r, ()) if len(idx[r]) <= 3)   # runs found in many pages: boilerplate
        if not c:
            out[k] = ("unmatched", None, 0.0, len(runs))
            continue
        d, n = c.most_common(1)[0]
        out[k] = ("matched" if n / len(runs) >= WEAK else "unmatched", d, round(n / len(runs), 3), len(runs))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--a", nargs="+", required=True); ap.add_argument("--b", nargs="+", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    if os.path.exists(a.out):
        sys.exit(f"refusing: {a.out} exists")
    A, B = side(a.a), side(a.b)
    ab, ba = best(A, B), best(B, A)
    with open(a.out, "x", encoding="utf-8") as f:
        f.write("# GENERATED by tools/ocr-copy-coverage.py: each page of side A and of side B, its best counterpart in the other "
                f"side by shared {K}-word runs, the share, and its runs. «unmatched» = a lead for a look, not a missing page.\n")
        f.write("side\titem\tpage\tverdict\tbest item\tbest page\tshare\truns\n")
        for s, res in (("A", ab), ("B", ba)):
            for (it, pg), (v, d, sh, n) in sorted(res.items()):
                f.write(f"{s}\t{it}\t{pg}\t{v}\t{d[0] if d else ''}\t{d[1] if d else ''}\t{sh}\t{n}\n")
    for s, res in (("A", ab), ("B", ba)):
        c = collections.Counter(v for v, *_ in res.values())
        print(f"side {s}: {len(res)} pages; " + ", ".join(f"{k} {n}" for k, n in c.most_common()))
    print("→", a.out)


if __name__ == "__main__":
    main()
