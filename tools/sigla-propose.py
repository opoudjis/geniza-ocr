#!/usr/bin/env python3
"""The sigla's check and review document (2026-10-24; the editor; to the options: periodicals «LSJ-style,
AmEsp», books «Author + year, Joss98», sign-off).

Reads profiles/SIGLA.tsv (one row a work: siglum, match, label, entry, old, status, note), the item table
(OCR-ITEM-TABLE.tsv, its «key» the item's permanent key, OCR-ITEM-KEYS.tsv), the newest dowse triage
(ocr/method/DOWSE-TRIAGE-*.tsv, for the tiers) and profiles/WORK-CODES.tsv (the codes in use). Checks: every siglum once;
every «match» a valid pattern; each item matched by at most one row; every item of tiers 0–3 matched; every code in use
named in some row's «old». Prints the counts; with --write PATH (create-only), the review document: every proposed row in
full, the works of tiers 0–3 no row matches with a siglum proposed by the rule, the items two rows match, the codes in use
no row names.

  python3 tools/sigla-propose.py [--tiers 0,1,2,3] [--write ocr/method/SIGLA-REVIEW-‹date›.md [--again]]
"""
import glob, os, re, sys
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
G = os.path.join(ROOT, "published", "heterophony-resources", "geniza")

def rows(path):
    out = []
    lines = [l.rstrip("\n") for l in open(path, encoding="utf-8") if not l.startswith("#")]
    head = lines[0].split("\t")
    for l in lines[1:]:
        if l.strip(): out.append(dict(zip(head, l.split("\t"))))
    return out

def sigla():
    return rows(os.path.join(G, "profiles", "SIGLA.tsv"))

def items():
    """item -> (title_key, year, key, kind) from the item table."""
    out = {}
    for r in rows(os.path.join(G, "OCR-ITEM-TABLE.tsv")):
        if r.get("key"): out[r["item"]] = (r.get("title_key", ""), r.get("year", ""), r["key"], r.get("kind", ""))
    return out

def tiers():
    """title_key -> tier, from the newest triage."""
    ps = sorted(glob.glob(os.path.join(G, "ocr", "method", "DOWSE-TRIAGE-*.tsv")))
    return ({r["title_key"].replace("[not in the item table] ", ""): r["tier"] for r in rows(ps[-1])}, os.path.basename(ps[-1])) if ps else ({}, "")

def codes_in_use():
    return [(r["pattern"], r["code"]) for r in rows(os.path.join(G, "profiles", "WORK-CODES.tsv")) if r.get("code")]

STOP = {"la", "le", "les", "de", "des", "du", "di", "da", "the", "of", "and", "kaj", "pri", "en", "el", "al", "por", "un", "une",
        "banq", "pub", "dokumen", "reu", "bhs", "pg", "kul", "anno", "part", "vol"}
def rule(key):
    """The rule's siglum for a work no row has (books: «Author + year», Joss98): the key's first word, capitalised, four
    letters at most, and the two-digit year of the first year in the key; a work with no year, the first word alone."""
    ws = [w for w in key.split("-") if w and w not in STOP and not w.isdigit()]
    yr = re.search(r"(?<!\d)(1[5-9]\d\d|20\d\d)(?!\d)", key)
    head = (ws[0][:4].capitalize() if ws else key[:4].capitalize())
    return head + (yr.group(1)[2:] if yr else "")

def page(S, path):
    """THE PUBLISHED SIGLA PAGE (2026-10-25; the editor, on prosopografio/README.md): every signed siglum with its work in Esperanto (profiles/SIGLA-EO.tsv),
    alphabetically, for the reader of a biography's references; rewritten at each run (the page is derived)."""
    import unicodedata
    eo = {r["siglum"]: r["verko"] for r in rows(os.path.join(G, "profiles", "SIGLA-EO.tsv"))}
    signed = [s for s in S if s.get("status") == "signed"]
    missing = [s["siglum"] for s in signed if s["siglum"] not in eo]
    if missing: sys.exit("refusing: no Esperanto entry in profiles/SIGLA-EO.tsv for " + ", ".join(missing))
    fold = lambda x: "".join(c for c in unicodedata.normalize("NFD", x.lower()) if unicodedata.category(c) != "Mn")
    L = ["# Siglaro", "", "_La sigloj, per kiuj la biografioj citas siajn fontojn._", "",
         "<!-- GENERATED by tools/sigla-propose.py --page from profiles/SIGLA.tsv and profiles/SIGLA-EO.tsv. Do not edit here. -->", "",
         # one definition a line, the term in bold (the editor, 2026-10-25 11:4x, via Miles
         #)
         "Ĉiu verko, el kiu la prosopografio prenas faktojn, havas unu **siglon**, la saman en ĉiuj biografioj. "
         "La siglo restas por ĉiam; la litero validas por unu legado de la fonto. La partoj de etikedo:", "",
         "- **AmEsp 1910.3:14a**: la siglo (AmEsp, *Amerika Esperantisto*), la jaro kaj la numero (1910.3), post la dupunkto "
         "la presita paĝo (14), kiel la paĝo mem ĝin presas, kaj la litero de la fakto sur tiu paĝo (a).",
         "- **Korĵ05:120m**: ĉe libro la siglo jam portas la jaron de la verko; Korĵenkov 2005, paĝo 120.",
         "- **∴15**: paĝo, kies numero ne legeblas en la skanaĵo; la numero eltirita el la paĝigo de la numero aŭ de la volumo.",
         "- **[15]**: paĝo de verko, kiu presas neniujn numerojn, nombrita.",
         "- **[kovrilo]**, **[interna kovrilo]**: la kovriloj.",
         "- **[PDF 14]**: la 14-a paĝo de la skanaĵo, nur kie neniu el la supraj eblas.",
         "- **¶12**: la 12-a alineo de tajpita teksto.",
         "- **l.40**: la 40-a linio de konservita retpaĝo.",
         "- **Rete**: kie la verko legeblas rete (la paĝo de la titolo ĉe ANNO, la dosierujo ĉe BitArkivo, la serĉo ĉe "
         "archive.org); la referencoj de ĉiu biografio donas la ligilon al ĉiu citita numero.", "",
         "Pli pri la etikedoj kaj la markoj de la biografioj: la ŝlosilo, `sxlosilo.md`.", "",
         f"La siglaro havas {len(signed)} siglojn.", "", "| Siglo | Verko | Rete |", "|---|---|---|"]
    import sigla as SG
    nowhere = []
    for s in sorted(signed, key=lambda s: fold(s["siglum"])):
        w = SG.work_online(re.compile(s["match"]), s["siglum"])
        if not w: nowhere.append(s["siglum"])
        L.append(f"| **{s['siglum']}** | {eo[s['siglum']]} | " + (" · ".join(f"[{h}]({SG.href(u)})" for h, u, _ in w) or "—") + " |")
    open(path, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print(f"wrote {os.path.relpath(path, ROOT)}: {len(signed)} sigla; no online location in the item table for {len(nowhere)}: " + ", ".join(nowhere))

def main():
    a = sys.argv[1:]
    if "--page" in a:
        return page(sigla(), a[a.index("--page") + 1] if len(a) > a.index("--page") + 1 and not a[a.index("--page") + 1].startswith("--")
                    else os.path.join(G, "prosopografio", "siglaro.md"))
    want = set((a[a.index("--tiers") + 1] if "--tiers" in a else "0,1,2,3").split(","))
    out = a[a.index("--write") + 1] if "--write" in a else None
    S, I, (T, tname), C = sigla(), items(), tiers(), codes_in_use()
    faults = []
    seen = defaultdict(int)
    for s in S: seen[s["siglum"]] += 1
    faults += [f"siglum twice: {k}" for k, n in seen.items() if n > 1]
    rx = {}
    for s in S:
        try: rx[s["siglum"]] = re.compile(s["match"])
        except re.error as e: faults.append(f"{s['siglum']}: the match does not compile ({e})")
    hit, double = defaultdict(list), []
    for it, (tk, yr, key, kind) in I.items():
        m = [s["siglum"] for s in S if s["siglum"] in rx and rx[s["siglum"]].search(key)]
        if len(m) > 1: double.append((key, m))
        if m: hit[m[0]].append((key, tk, yr))
    # THE PLACE RULES (profiles/SIGLA-PLACES.tsv, 2026-10-24): every siglum there in the register; every item of a work
    # with rules matched by one of them (else its lines get no label)
    import sigla as SG
    pl = SG.rows(SG.PLACES)
    faults += [f"SIGLA-PLACES.tsv names {s}, which the register lacks" for s in sorted({r["siglum"] for r in pl} - set(seen))]
    for r in pl:
        try: re.compile(r["pattern"])
        except re.error as e: faults.append(f"SIGLA-PLACES.tsv, {r['siglum']}: «{r['pattern']}» does not compile ({e})")
    rules = {s: [] for s in seen}
    for r in pl:
        try: rules[r["siglum"]].append((re.compile(r["pattern"]), r["template"]))
        except (re.error, KeyError): pass
    noplace = [(s, k) for s, v in hit.items() for k, _t, _y in v if rules.get(s) and SG.place(k, rules[s]) is None]
    unmatched = defaultdict(list)
    for it, (tk, yr, key, kind) in I.items():
        if T.get(tk) in want and not any(key == k for s in hit.values() for k, _t, _y in s):
            unmatched[(T[tk], tk)].append(key)
    named = {c.strip() for s in S for c in s.get("old", "").split(",")}
    # a code with the key's groups in it («AE\1-\2») is named by its letters before the first group
    uncovered = [(p, c) for p, c in C if c.split("\\")[0] not in named]
    # «retired» (2026-10-25, Garson: a withdrawn item's siglum, kept so it is never reused, off the published page)
    faults += [f"{s['siglum']}: status «{s.get('status', '')}», not «proposed», «signed» or «retired» (a column missing?)" for s in S
               if s.get("status") not in ("proposed", "signed", "retired")]
    proposed = [s for s in S if s.get("status") == "proposed"]
    print(f"{len(S)} sigla ({len(proposed)} proposed, {len(S) - len(proposed)} signed); {sum(len(v) for v in hit.values())} items matched; "
          f"tiers {','.join(sorted(want))} ({tname}): {len(unmatched)} works no row matches; {len(double)} items two rows match; "
          f"{len(uncovered)} codes in use no row names; {len(noplace)} items no place rule of their work matches; {len(faults)} faults"
          + ("".join(f"\n  FAULT {f}" for f in faults))
          + (("\n  no place: " + ", ".join(f"{s} {k}" for s, k in sorted(noplace)[:40]) + (" …" if len(noplace) > 40 else "")) if noplace else ""))
    if not out: return 0 if not faults else 1
    def years(v):
        ys = sorted({y for _k, _t, y in v if y})
        return f"{ys[0]}–{ys[-1]}" if len(ys) > 1 else (ys[0] if ys else "no year")
    doc = ["# The sigla, proposed (2026-10-24)", "",
           f"`[tools/sigla-propose.py --write: profiles/SIGLA.tsv checked against the item table (OCR-ITEM-TABLE.tsv, the items' permanent keys) and the triage {tname}; for the editor's sign-off, row by row. A signed siglum is never changed.]`", "",
           "**The rulings this follows** (the editor, 2026-10-24 20:4x): periodicals LSJ-style, from the title's words («AmEsp»); books the author and the two-digit year («Joss98»); tiers 0–3 first, the rest by the same rule as they enter a biography, each listed for sign-off before use. The label adds the place: a periodical's year and issue, or its volume, then the page and the line's letter («AmEsp 1910.3:14a»); a book's page or ¶ («Joss98:31a»).", "",
           "**The principle** (the editor, 2026-10-24 21:0x, on the first proposals; written out in profiles/SIGLA.tsv's header): mnemonic over short, whole syllables, single letters only as an initialism an Esperanto reader recovers; a town in an Esperanto source in its Esperanto form («RapĜen06»); diacritics kept («Korĵ05», «Künz06»); the year only where it tells works apart; collisions taken in advance («Künz20a», «Künz20b»). Each row's note says whether the form is the editor's or Ezri's reading of the principle.", "",
           "**To sign:** a row as it stands, «sign ‹siglum›»; a changed siglum, «‹siglum› → ‹yours›»; or «sign all but …». The questions are in the rows' notes.", "",
           "## For the editor: the sigla proposed", "",
           "| siglum | a label | the work | items | the code now | note |", "|---|---|---|---|---|---|"]
    for s in proposed:
        v = hit.get(s["siglum"], [])
        n = f"{len(v)} ({years(v)})" if v else "outside the item table"
        doc.append(f"| **{s['siglum']}** | {s['label']} | {s['entry']} | {n} | {s.get('old', '')} | {s.get('note', '')} |")
    doc += ["", f"## For the editor: the works of tiers {', '.join(sorted(want))} no row has yet ({len(unmatched)}), with the rule's siglum", "",
            "| tier | the work (its title key) | its items' keys | the rule's siglum |", "|---|---|---|---|"]
    for (tr, tk), ks in sorted(unmatched.items()):
        doc.append(f"| {tr} | {tk} | {', '.join(sorted(ks)[:6])}{' …' if len(ks) > 6 else ''} ({len(ks)}) | {rule(sorted(ks)[0])} |")
    doc += ["", "## For the record", "", f"### Items two rows match ({len(double)}; the first row takes them)", ""]
    doc += [f"- {k}: {', '.join(m)}" for k, m in sorted(double)] or ["(none)"]
    doc += ["", f"### Codes in use that no row names in «old» ({len(uncovered)})", ""]
    doc += [f"- {c} (`{p}`)" for p, c in uncovered] or ["(none)"]
    doc += ["", "### Faults", ""] + ([f"- {f}" for f in faults] or ["(none)"])
    # create-only; --again rewrites a document this tool wrote that git does not track (the dowse runbook, P5)
    if os.path.exists(out) and "--again" in a:
        import subprocess
        if subprocess.run(["git", "-C", ROOT, "ls-files", "--error-unmatch", out], capture_output=True).returncode == 0:
            sys.exit(f"refusing: {os.path.relpath(out, ROOT)} is tracked")
        os.remove(out)
    with open(out, "x", encoding="utf-8") as fh: fh.write("\n".join(doc) + "\n")
    print(f"wrote {os.path.relpath(out, ROOT)}")
    return 0 if not faults else 1

if __name__ == "__main__":
    sys.exit(main())
