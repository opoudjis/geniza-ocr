#!/usr/bin/env python3
r"""ocr-name-search — find a NAME in OCR text the way an absence claim needs: forgiving of line breaks, column
splits and one- or two-letter misreadings.

    tools/ocr-name-search.py "<name>" <text file> [...]      # prints each hit: file, how it matched, the text
    (import) find(name, text) -> list of hits

WHY (2026-09-28 19:17, the editor ruled that the search be fixed and the audit redone, on the final audit (an internal
record, 2026-09-28, not published): 84% of printed names findable by exact-ish search). The misses were largely a SEARCH problem: names hyphenated at a line end
(«Za-/menhof», «Kaba-/nov»), names split by the OCR's interleaving of two columns («Apple-» … «baum»), a letter or
two misread («Iglauer» → «Jglauer», «Döhler» → «D6hler»). An absence claim must search so as to catch those.
HOW:
1. the text is normalised: Unicode NFC; words hyphenated at a line end joined («Za-\nmenhof» → «Zamenhof»);
2. a word and the name are FOLDED: lower case; diacritics and pre-reform Cyrillic letters folded (ĉ→c, ä→a, ѣ→е,
   і→и, final ъ dropped); digits that OCR confuses with letters mapped (0→o, 1→l, 5→s, 6→o, 8→b);
3. a hit is a word (or two adjacent words joined, or a fragment ending in «-» joined with any fragment within the
   next WINDOW words — a column split) within EDIT letters of the name's surname: 1 for up to 6 letters, 2 beyond.
Generous on purpose: a false hit costs a look; a false absence costs a wrong finding.
FIXED 2026-09-29 (G5 name recall, an internal record, 2026-09-29, not published): four faults made names present in the text
unfindable, so they are now handled:
4. a line-end hyphen is NOT joined in advance (that fused real compounds: «Dietterle-/statistiko» became one word);
   the join is tried as a candidate («two words joined»), and so are the parts of every hyphenated word
   («Grosjean-Maupin» → «Grosjean», «Maupin»; also «/» and apostrophes);
5. Russian case endings: a Cyrillic surname matches its inflected forms («Бржостовскій» ~ «Бржостовскаго»,
   «Маринова» ~ «Мариновой», «Коцынъ» ~ «Коцынымъ»): the ending is stripped from both before comparing;
6. a Latin-letter name is also compared with Cyrillic words transliterated («Lebedev» ~ «Лебедевъ», «Ĉirikov» ~
   «Чириковъ»), and a Cyrillic name with Latin words;
7. a name given in two forms («Яковъ Бородкинъ / Jakov Borodkin», «A. Nedoshivin (А. Недошивин)») is found if
   EITHER form is.
ADDED 2026-09-30 (approved by the editor; failure-map row 5b): 8. SMALL CAPITALS — a Latin name of 5+ letters is also compared
   with the letters small caps are misread between folded together (r/n/w, g/c, d/p), so «Bréon» finds «Bnéow».
ADDED 2026-10-02 (the editor's choice of option 3): 9. a name GLUED to a following short function word («asnesde» = «Asnes de»).
ADDED 2026-10-05 (approved by the editor, on the accent survey `docs/OCR-ACCENT-SURVEY-2026-10-05.md`; the digit
   map of step 2 was empirical, not a survey): 10. the fold also takes compatibility forms apart (NFKC: the ligatures
   ﬁ ﬂ ﬀ ﬃ ﬅ of born-digital text layers become fi fl ff ffi ft) and maps the letters that carry no separable accent:
   ł→l, ø→o, đ→d, ı→i, ß→ss, æ→ae, œ→oe; and ъ is taken as ь (OCR confuses them); 11. MEASURED CONFUSIONS — what OCR
   was measured to write in place of an accented Latin or a Cyrillic letter, where the fold does not absorb it
   (é→ĉ, ř→f, ü→ii, ѣ→ъ, і→ш …: `ocr-name-search-confusions.tsv`, generated by `ocr-accent-survey.py`, old and modern
   print kept apart there, both tried here): the name is also compared in those spellings, at most MAXV of them.
"""
import csv, itertools, os, re, sys, unicodedata

WINDOW = 40
MAXV = 64
_DIG = str.maketrans({"0": "o", "1": "l", "5": "s", "6": "o", "8": "b"})
_CYR = str.maketrans({"ѣ": "е", "і": "и", "ѳ": "ф", "ѵ": "и"})
_LET = str.maketrans({"ł": "l", "ø": "o", "đ": "d", "ı": "i", "ß": "ss", "æ": "ae", "œ": "oe"})


def fold(w):
    w = unicodedata.normalize("NFKC", w).lower().translate(_DIG).translate(_CYR).translate(_LET)
    w = "".join(c for c in unicodedata.normalize("NFD", w) if unicodedata.category(c) != "Mn")
    # punctuation first, then the final ъ, then ъ as ь (FIXED 2026-10-06: ъ→ь before the punctuation went turned
    # «Постииковымъ:» into «…ымь», which is no Russian ending, and lost «Постниковъ»)
    w = re.sub(r"[^\w]", "", w)
    return re.sub(r"ъ$", "", w).replace("ъ", "ь")


def _confusions():
    """letter → what OCR writes in its place, most frequent first (old and modern print together)."""
    p = os.path.join(os.path.dirname(os.path.abspath(__file__)), "ocr-name-search-confusions.tsv")
    if not os.path.exists(p):
        return {}
    best = {}
    for r in csv.DictReader((l for l in open(p, encoding="utf-8") if not l.startswith("#")), delimiter="\t"):
        k = (r["letter"], r["written"])
        best[k] = max(best.get(k, 0.0), float(r["share"]))
    conf = {}
    for (ch, w), s in sorted(best.items(), key=lambda kv: -kv[1]):
        conf.setdefault(ch, []).append(w)
    return conf


CONF = _confusions()


def variants(word):
    """the name as OCR was measured to misspell it: each letter with confusions tried in each of them; at most MAXV
    spellings, the commonest confusions first (fewer per letter when the name has many such letters)."""
    w = unicodedata.normalize("NFC", word.lower())
    for k in (4, 2, 1):
        opts = [[c] + CONF.get(c, [])[:k] for c in w]
        n = 1
        for o in opts:
            n *= len(o)
        if n <= MAXV:
            break
    # each spelling with the number of letters it changed: a measured confusion USES UP the allowance (step 11, 2026-10-06)
    return [("".join(p), sum(x != c for x, c in zip(p, w)))
            for p in itertools.islice(itertools.product(*opts), MAXV)][1:]


def edits(a, b, cap):
    """Levenshtein distance, stopping early above cap."""
    if abs(len(a) - len(b)) > cap:
        return cap + 1
    prev = list(range(len(b) + 1))
    for i, ca in enumerate(a, 1):
        cur = [i] + [0] * len(b)
        for j, cb in enumerate(b, 1):
            cur[j] = min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (ca != cb))
        if min(cur) > cap:
            return cap + 1
        prev = cur
    return prev[-1]


def normalise(text):
    return unicodedata.normalize("NFKC", text)


_LAT = {"а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e", "ж": "zh", "з": "z", "и": "i", "й": "j",
        "к": "k", "л": "l", "м": "m", "н": "n", "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u", "ф": "f",
        "х": "h", "ц": "c", "ч": "ch", "ш": "sh", "щ": "shch", "ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "ju", "я": "ja"}
# Russian case endings, longest first; a surname stem is compared with the ending stripped from both words
_ENDS = sorted(["аго", "ого", "его", "ому", "ему", "ыми", "ими", "ымъ", "имъ", "ым", "им", "ом", "ем", "ой", "ей",
                "ою", "ею", "ую", "юю", "ая", "яя", "ий", "ии", "ый", "ые", "ых", "их", "а", "я", "у", "ю", "е", "ы",
                "и", "о"], key=len, reverse=True)
_CYRRE = re.compile("[а-яё]")


def translit(w):
    return "".join(_LAT.get(c, c) for c in w)


def stem(w):
    for e in _ENDS:
        if w.endswith(e) and len(w) - len(e) >= 3:
            return w[:-len(e)]
    return w


def stem_close(t, target, cap):
    """Two Cyrillic words, compared with a Russian case ending stripped from both. Shared with tools/ocr-dowse.py,
    which labels the tiers by it."""
    st, sg = stem(t), stem(target)
    if len(target) > 4:
        return edits(st, sg, cap) <= cap
    # A name of four letters or fewer may have an ending OR a misread letter, not both (the editor's decision,
    # 2026-10-06): «Кабе» stems to «каб», and one letter more matched «кап», «кат», «каро», «казо» — 5,701 of 6,174
    # near hits in one journal-year. For such a name the stems must be equal («Каба», «Кабу» still match) ...
    if st == sg:
        return True
    # ... except (a refinement the editor added the same day, conditioned on word length) when the word on the page
    # is longer than the name, so it really carries an ending, and the name's own stem keeps four letters: «Бсйна»,
    # «Бсйномъ» are Бейн declined and misread; «Табого», «Капою» are not Кабе (its stem «каб» is too short).
    return len(sg) >= 4 and len(t) > len(target) and st != t and edits(st, sg, cap) <= cap


def close(t, target, cap):
    if not t:
        return False
    # A word of two letters or fewer matches ONLY exactly (the editor's decision, 2026-10-06: two-letter names are not
    # searched for, and if they ever were, only an exact match would do). Without this, tolerances stacked:
    # «Кабе» stripped of the ending «е» became «каб», and one misread letter more matched «ка» — 27,058 hits in one
    # journal-year; transliteration did the same («ка» → «ka» against «kabe»). A name broken into small pieces is
    # still found by the joins, which compare the pieces joined.
    if len(t) <= 2:
        return t == target
    if edits(t, target, cap) <= cap:
        return True
    tc, gc = bool(_CYRRE.search(t)), bool(_CYRRE.search(target))
    if tc and gc and stem_close(t, target, cap):
        return True
    if tc != gc:  # one Cyrillic, one Latin: compare in Latin letters, whole and with the Cyrillic word's ending stripped
        c, l = (t, target) if tc else (target, t)
        return any(edits(translit(x), l, cap + 1) <= cap + 1 for x in (c, stem(c)))
    # SMALL CAPITALS (approved by the editor 2026-09-30 23:0x; failure-map row 5b): a name set in small caps is misread with
    # letter confusions the ordinary allowance does not cover («BRÉON» → «Bnéow», «HAUGG» → «Haucc», «HODLER» →
    # «Hopren»). A Latin name of 5+ letters is compared once more with the confusable letters folded together.
    if not tc and not gc and len(target) >= 5 and edits(t.translate(_SC), target.translate(_SC), cap) <= cap:
        return True
    # GLUED TO THE NEXT WORD (the editor's choice of option 3, 2026-10-02; G5 final, ondodeesperanto.1910.04 p.2: «Asnes de» → «asnesde»,
    # «Moĵaev de» → «mojaevde»). A name of 4+ letters followed, with no space, by a short function word.
    if len(target) >= 4 and len(t) > len(target):
        for k in range(len(target) - 1, len(target) + 2):
            if t[k:] in _GLUE and edits(t[:k], target, cap) <= cap:
                return True
    return False


_GLUE = {"de", "da", "la", "kaj", "en", "el", "al", "el", "un", "und", "et", "ou", "y", "i", "e", "di", "ed"}


# small-caps confusions, each group folded to one letter (G5 re-sample 2026-09-30: r/n/w, g/c, d/p)
_SC = str.maketrans({"r": "n", "w": "n", "g": "c", "d": "p"})


def forms(name):
    """A name may come in two forms: «X / Y», «X (Y)»."""
    return [f for f in re.split(r"\s*[/()]\s*", name) if re.search(r"[^\W\d_]{2,}", f)] or [name]


def name_targets(f):
    """One form of a name → the spellings it is compared in: [(folded spelling, why, allowance)], the name as written
    first. Shared by find() and the corpus index (tools/ocr_index.py), so the two cannot drift apart."""
    longest = max(re.findall(r"[^\W\d_]+", f), key=len)
    target = fold(longest)
    cap = 1 if len(target) <= 6 else 2
    # the name as written, then as OCR was measured to misspell it (step 11). A spelling made by n measured
    # confusions keeps only cap - n of the allowance (FIXED 2026-10-06: with the full allowance on top, a dropped
    # letter let «Méray» → «mray» match «may» — 269,625 hits for one name over the corpus).
    best = {}
    for v, n in variants(longest):
        fv = fold(v)
        if fv and fv != target:
            best[fv] = max(best.get(fv, -1), cap - n)
    return [(target, "", cap)] + [(fv, " (measured OCR confusion)", c) for fv, c in sorted(best.items()) if c >= 0]


def find(name, text):
    """Hits for the name's LONGEST word (the surname, usually) in text: [(how, matched text)]. Either form of a
    two-form name counts."""
    hits = []
    raw = normalise(text).split()
    toks = [fold(t) for t in raw]
    parts = [[fold(x) for x in re.split(r"[-‐¬/'’]", r) if fold(x)] for r in raw]
    for f in forms(name):
        targets = name_targets(f)
        memo = {}

        def near(t):
            # each distinct word is compared once per search (2026-10-06: words repeat; hours became minutes)
            if t not in memo:
                memo[t] = next((why for tg, why, c in targets if close(t, tg, c)), None)
            return memo[t]

        for i, t in enumerate(toks):
            w = near(t)
            if w is not None:
                hits.append(("word" + w, raw[i]))
            elif len(parts[i]) > 1:
                for x in parts[i]:
                    w = near(x)
                    if w is not None:
                        hits.append(("part of a hyphenated word" + w, raw[i])); break
            if i + 1 < len(toks) and toks[i + 1]:
                w = near(t + toks[i + 1])
                if w is not None:
                    hits.append(("two words joined" + w, raw[i] + " " + raw[i + 1]))
            if raw[i].endswith(("-", "¬")) and t and any(tg.startswith(t[:max(2, len(t) - 1)]) for tg, _, _ in targets):
                for j in range(i + 1, min(len(toks), i + 1 + WINDOW)):
                    w = near(t + toks[j]) if toks[j] else None
                    if w is not None:
                        hits.append(("column split" + w, raw[i] + " … " + raw[j])); break
        if hits:
            break
    return hits


if __name__ == "__main__":
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    for f in sys.argv[2:]:
        for how, m in find(sys.argv[1], open(f, encoding="utf-8", errors="ignore").read()):
            print(f"{f}\t{how}\t{m}")
