#!/usr/bin/env python3
"""ocr-corpus-lexicon — every word form attested in the geniza OCR, folded as the name search folds it, with how often
and in how many items it occurs (suggested by the editor on 2026-10-06, after the first
whole-corpus searches flooded).

    tools/ocr-corpus-lexicon.py --write <new.tsv> [--jobs 8]

Reads, per item: the search text (`sources/ocr-rendersearch/<item>.txt`) and the texts in another alphabet
(`ocr-rendersearch-rus/`, `-hye/`, `-kat/`). The every-reading texts are left out: they repeat the readings, and
would count words twice. Writes one TSV (refused if it exists): folded form · occurrences · items · one raw spelling.
It is DERIVED from copyright text: keep it under `sources/` (untracked). Dowse reads it to show, for each word a
search matched, how common that word is: a match on a word that occurs 10,000 times is noise, not a find.
"""
import argparse, collections, glob, importlib.util, os, sys
from multiprocessing import Pool

HERE = os.path.dirname(os.path.abspath(__file__))
S = os.path.join(HERE, "..", "published", "heterophony-resources", "geniza", "sources")
_s = importlib.util.spec_from_file_location("ns", os.path.join(HERE, "ocr-name-search.py"))
NS = importlib.util.module_from_spec(_s); _s.loader.exec_module(NS)


def count(item):
    occ, raw = collections.Counter(), {}
    for d in ("ocr-rendersearch", "ocr-rendersearch-rus", "ocr-rendersearch-hye", "ocr-rendersearch-kat"):
        f = os.path.join(S, d, item + ".txt")
        if not os.path.exists(f):
            continue
        for t in NS.normalise(open(f, encoding="utf-8", errors="ignore").read()).split():
            ft = NS.fold(t)
            if ft and not ft.isdigit():
                occ[ft] += 1
                raw.setdefault(ft, t)
    return occ, raw


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", required=True); ap.add_argument("--jobs", type=int, default=8)
    a = ap.parse_args()
    if os.path.exists(a.write):
        sys.exit(f"refusing: {a.write} exists")
    items = sorted(os.path.basename(f)[:-4] for f in glob.glob(os.path.join(S, "ocr-rendersearch", "*.txt")))
    occ, nitems, raw = collections.Counter(), collections.Counter(), {}
    with Pool(a.jobs) as pool:
        for o, r in pool.imap_unordered(count, items, chunksize=4):
            occ.update(o); nitems.update(o.keys())
            for k, v in r.items():
                raw.setdefault(k, v)
    with open(a.write, "w", encoding="utf-8") as f:
        f.write(f"# GENERATED by tools/ocr-corpus-lexicon.py over {len(items)} items. Derived from copyright text: "
                f"keep under sources/, untracked. Do not hand-edit — re-run it.\n")
        f.write("form\toccurrences\titems\tas_written\n")
        for k, n in occ.most_common():
            f.write(f"{k}\t{n}\t{nitems[k]}\t{raw[k]}\n")
    print(f"{len(items)} items · {len(occ)} distinct forms · {sum(occ.values())} words → {a.write}")


if __name__ == "__main__":
    main()
