#!/usr/bin/env python3
"""The online location of every item, for the sigla page and the biographies' references (2026-10-25; the editor:
).

    python3 tools/online-locations.py [--again]

Writes profiles/ONLINE-LOCATIONS.tsv (create-only; --again rewrites it, being generated): one row an item key of the item
table that has a location, with where it came from. In this order:
  1. the item table's «origin», where it gives a URL (archive.org, BitArkivo);
  2. the ÖNB's «Zitierlink» on the cover sheet of a whole-work PDF from data.onb.ac.at (sources/<item>.pdf, page 1,
     read by pdftotext: the OCR of that page garbles it, «rep/1002AAAO» for «rep/1002AAA0»);
  2b. a spider's map of our holdings to their site, sources/web-*/URLS-*.tsv (Künzli's, 2026-10-25), by the file's stem;
  3. a saved web page or download registered in sources/_WEB-DOWNLOADS.tsv under the item's file name, the first URL of
     its note;
(A born-digital text's own first URL was a fourth way, withdrawn the same day: it is usually a reference inside the text.)
The works' own locations (an ANNO title, a fetch log, an archive.org identifier) are not here: they are in the hand-kept
profiles/SIGLA-ONLINE.tsv, read with this file by tools/sigla.py. Ezri, 2026-10-25."""
import os, re, subprocess, sys, unicodedata
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import sigla

G = sigla.G
OUT = os.path.join(G, "profiles", "ONLINE-LOCATIONS.tsv")
URL = re.compile(r"(?:https?://|\b(?=[a-z0-9.-]+\.[a-z]{2,}/))[^\s»«,;)>\]`]+")

def web_downloads():
    """file stem (NFC) -> the first URL of its note in sources/_WEB-DOWNLOADS.tsv."""
    out = {}
    for l in open(os.path.join(G, "sources", "_WEB-DOWNLOADS.tsv"), encoding="utf-8"):
        f = l.rstrip("\n").split("\t")
        if len(f) < 4 or f[0] == "path": continue
        m = URL.search(f[3])
        if not m: continue
        u = m.group(0).rstrip(".")
        if not u.startswith("http"): u = "https://" + u
        stem = unicodedata.normalize("NFC", os.path.splitext(os.path.basename(f[0]))[0])
        out.setdefault(stem, u)
    return out

def zitierlink(item):
    p = os.path.join(G, "sources", item + ".pdf")
    if not os.path.isfile(p): return None
    try:
        t = subprocess.run(["pdftotext", "-f", "1", "-l", "1", p, "-"], capture_output=True, text=True, timeout=60).stdout
    except Exception:
        return None
    m = re.search(r"Zitierlink:\s*(https?://data\.onb\.ac\.at/\S+)", t)
    return m.group(1) if m else None

def main():
    if os.path.exists(OUT) and "--again" not in sys.argv:
        sys.exit(f"refusing: {os.path.relpath(OUT, G)} exists (--again rewrites it)")
    wd = web_downloads()
    # THE SPIDERS' MAPS (2026-10-25; the editor
    #): sources/web-*/URLS-*.tsv, a held file's path and its URL;
    # an item whose name is the file's stem takes it
    maps = {}
    import glob
    for mp in sorted(glob.glob(os.path.join(G, "sources", "web-*", "URLS-*.tsv"))):
        for l in open(mp, encoding="utf-8"):
            f = l.rstrip("\n").split("\t")
            if len(f) < 2 or l.startswith(("#", "path\t")): continue
            stem = unicodedata.normalize("NFC", os.path.splitext(os.path.basename(f[0]))[0]).lower()
            maps.setdefault(stem, (f[1], os.path.relpath(mp, G)))
    rows, count = [], {}
    for key, r in sorted(sigla.table().items()):
        item, o = r["item"].strip(), r.get("origin", "")
        u, why = None, ""
        m = re.search(r"https?://[^\s»«,;)]+", o)
        if m: u, why = m.group(0).rstrip("."), "the item table's origin"
        if not u:
            z = zitierlink(item)
            if z: u, why = z, f"the ÖNB Zitierlink, sources/{item}.pdf page 1"
        if not u:
            s = maps.get(unicodedata.normalize("NFC", item).lower())
            if s: u, why = s   # a spider's map of a holding to its site (Künzli's, 2026-10-25)
        if not u:
            s = wd.get(unicodedata.normalize("NFC", item)) or wd.get(key)
            if s: u, why = s, "sources/_WEB-DOWNLOADS.tsv"
        # (a born-digital text's first URL is NOT its location: in a Wikipedia article it is one of the references, the
        # editor, 2026-10-25; the rule withdrawn)
        if u:
            rows.append(f"{key}\t{u}\t{why}")
            k = "a born-digital text" if why.startswith("sources/born-digital") else why.split(",")[0]
            count[k] = count.get(k, 0) + 1
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("# ONLINE-LOCATIONS: GENERATED by tools/online-locations.py from the item table, the PDFs' ÖNB cover sheets, "
                 "sources/_WEB-DOWNLOADS.tsv and the born-digital texts. Do not hand-edit: re-run it with --again. The works' own "
                 "locations are in profiles/SIGLA-ONLINE.tsv (by hand).\nkey\turl\tfrom\n" + "\n".join(rows) + "\n")
    print(f"wrote {os.path.relpath(OUT, G)}: {len(rows)} of {len(sigla.table())} items; " + "; ".join(f"{k} {v}" for k, v in sorted(count.items())))

if __name__ == "__main__":
    main()
