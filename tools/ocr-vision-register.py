#!/usr/bin/env python3
r"""ocr-vision-register — every page that has had vision or a hand on it, from the files themselves.

    tools/ocr-vision-register.py [--out <geniza>/ocr/VISION-REGISTER.tsv]

WHY (the editor 2026-10-25 01:2x). They were tracked only as files, one
per page, in `sources/ocr-rendersearch/<item>/`; this lists them in one place, rebuilt from those files each time, so it
cannot go stale or disagree with them:
  vision      page-NNNN.vision.txt      the whole page read by vision: never again by snippets or a re-read
  vision-add  page-NNNN.vision-add.txt  lines the reading lost, added by vision: the rest of the page is still OCR
  names       page-NNNN.names.txt       name snippets read by vision (tools/ocr-name-crops.py); LEVEL says how widely
              they were cut: «every candidate» for the runs before the tiers (2026-10-24, all of Svisa Espero's name
              columns), else the small-capital tier (`tools/smallcaps-signals.py`) the run cut at, from its FILED.tsv's
              `tier` line; a page is owed a new pass only when a looser tier than its own is signed
  hand        page-NNNN.hand.txt        keyed by the editor
  ruled       page-NNNN.ruled.txt       read again as the editor's G1 ruling directed (not vision; listed so it is not
              re-read over)
Columns: item · page · reading · level · file date · snippet run (for names). Sorted by item and page.
WRITE-SET: --out alone, rewritten (a generated file).
"""
import argparse, glob, os, re, time

HERE = os.path.dirname(os.path.abspath(__file__))
G = os.path.join(HERE, "..", "published", "heterophony-resources", "geniza")
R = os.path.join(G, "sources", "ocr-rendersearch")
KINDS = ("vision", "vision-add", "names", "hand", "ruled")


def runs():
    """item, page → (run folder, level) from every name-crops run's KEY.tsv and FILED.tsv"""
    out = {}
    for d in sorted(glob.glob(os.path.join(G, "sources", "ocr-work", "name-crops*"))):
        fl = os.path.join(d, "FILED.tsv")
        if not os.path.exists(fl): continue
        level = "every candidate"
        for l in open(fl, encoding="utf-8"):
            m = re.match(r"tier\t(.+)", l)
            if m: level = "tier " + m.group(1).strip()
        for l in open(os.path.join(d, "KEY.tsv"), encoding="utf-8"):
            x = l.rstrip("\n").split("\t")
            if len(x) >= 4 and x[3].isdigit(): out.setdefault((x[2], int(x[3])), (os.path.basename(d), level))
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default=os.path.join(G, "ocr", "VISION-REGISTER.tsv")); a = ap.parse_args()
    rn = runs(); rows = []
    for f in glob.glob(os.path.join(R, "*", "page-*.txt")):
        m = re.fullmatch(r"page-(\d+)\.(vision|vision-add|names|hand|ruled)\.txt", os.path.basename(f))
        if not m: continue
        item, p, kind = os.path.basename(os.path.dirname(f)), int(m.group(1)), m.group(2)
        run, level = rn.get((item, p), ("", "")) if kind == "names" else ("", "")
        if kind == "names" and not level: level = "every candidate"
        rows.append((item, p, kind, level, time.strftime("%Y-%m-%d", time.localtime(os.path.getmtime(f))), run))
    rows.sort()
    with open(a.out, "w", encoding="utf-8") as w:
        w.write("# GENERATED by tools/ocr-vision-register.py from the page files in sources/ocr-rendersearch/; rebuild, "
                "don't edit. Pages with vision or a hand on them (the editor 2026-10-25: «so that they are not reconsidered "
                "for future iterations of cupel improvement»).\n")
        w.write("item\tpage\treading\tlevel\tfile date\tsnippet run\n")
        w.writelines("\t".join(map(str, r)) + "\n" for r in rows)
    c = {k: sum(1 for r in rows if r[2] == k) for k in KINDS}
    print(", ".join(f"{k} {v:,}" for k, v in c.items()) + f"; {len({(r[0], r[1]) for r in rows}):,} pages → {a.out}")


if __name__ == "__main__":
    main()
