#!/usr/bin/env python3
"""The directories of the corpus surveyed for the extractors (runbook D4c; 2026-10-29 11:5x, the editor): each address book, yearbook and members' list, its size, the opening of its text (the foreword, where the key to its
signs stands), a sample from its middle, and every line that names a sign or a numbering («steleto», «signo», «(*)»,
«numero»), so that each format is seen before its parser is written.

    tools/directory-survey.py [--out PATH]

Writes geniza/dowse/DIRECTORY-SURVEY-<today>.md (create-only). Reads the texts only. Ezri."""
import argparse, datetime, glob, os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
G = os.path.join(ROOT, "published", "heterophony-resources", "geniza")
OP, BD = os.path.join(G, "sources", "ocr-preferred"), os.path.join(G, "sources", "born-digital-text")

# (the title, its files, how many of them get excerpts: the rest are only counted)
TITLES = [
    ("Zamenhof's *Adresaro*, series 1–29 (1889–1908)", sorted(glob.glob(os.path.join(BD, "adresaro-*.txt"))),
     ["adresaro-1889-serio-01", "adresaro-1893-serio-13", "adresaro-1899-serio-20", "adresaro-1904-serio-25-1", "adresaro-1908-serio-29-2"]),
    ("*Tutmonda Jarlibro Esperantista* 1904–1910 (forewords: the signs' keys)", sorted(glob.glob(os.path.join(OP, "ANNO_e4d_19*0005.txt"))), None),
    ("*Oficiala Jarlibro* of UEA 1911–1914", sorted(glob.glob(os.path.join(OP, "OficialaJarlibro*.txt"))), None),
    ("*Jarlibro de Tutmonda Esperantista Kuracista Asocio* (T.E.K.A.) 1909–1910", sorted(glob.glob(os.path.join(OP, "ANNO_e7i_*.txt"))), None),
    ("*Hispana Jarlibro* 1906", [os.path.join(OP, "HispanaJarlibro.1906.txt")], None),
    ("The Polish address book 1909", [os.path.join(OP, "reu-pola-adresaro-1909.txt")], None),
    ("The Russian address book 1914", [os.path.join(BD, "reu-adresar_ru_1914.txt")], None),
    ("The Boulogne congress-goers 1905", [os.path.join(OP, "Adresaro de la kongresanoj en Boulogne-sur-Mer 1905.txt")], None),
    ("The first congress's members, an index (*Adresaro de UK-anoj* 1905; UK the Universala Kongreso, not the Lingva Komitato)", [os.path.join(OP, "Adresaro de UK-anoj 1905.txt")], None),
    ("The tenth congress's list, Paris 1914, and a «Nomaro de la kongresanoj» (found in the triage after the first survey)",
     [p for p in sorted(glob.glob(os.path.join(OP, "*ongresanoj*"))) if "Boulogne" not in p], None),
    ("The *Annuaire* 1901", [os.path.join(OP, "Annuaire.txt")], None),
    ("*Esperantista Poŝkalendaro* 1912", [os.path.join(OP, "EsperantistaPoshkalendaro.1912.txt")], None),
]
KEYS = re.compile(r"stelet|speciala signo|signas|signifas|\(\s?\*\s?\)|kursiv|grasaj liter|numero de la adres|n-ro de", re.I)
HEAD, MID, CUT = 18, 18, 170

def body(lines):
    return [l.rstrip("\n") for l in lines if l.strip() and not l.startswith("=== page")]

def excerpt(path):
    raw = open(path, encoding="utf-8", errors="replace").readlines()
    pages = sum(1 for l in raw if l.startswith("=== page"))
    b = body(raw)
    words = sum(len(l.split()) for l in b)
    keyl = [(n, l.strip()) for n, l in enumerate(raw, 1) if KEYS.search(l)][:8]
    m = len(b) // 2
    out = [f"### `{os.path.relpath(path, G)}`", "", f"{pages or '—'} PDF pages, {len(b):,} lines, {words:,} words.", "",
           "The opening:", "", "```"] + [l[:CUT] for l in b[:HEAD]] + ["```", "", f"The middle (from line {m} of the text's lines):", "", "```"] \
          + [l[:CUT] for l in b[m:m + MID]] + ["```", ""]
    if keyl: out += ["Lines naming a sign or a numbering:", ""] + [f"- l. {n}: «{l[:CUT]}»" for n, l in keyl] + [""]
    return out, len(b), words

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default=os.path.join(G, "dowse", f"DIRECTORY-SURVEY-{datetime.date.today().isoformat()}.md"))
    a = ap.parse_args()
    if os.path.exists(a.out): sys.exit(f"refusing to overwrite {a.out}")
    doc = ["# The directories surveyed", "", "`[GENERATED by tools/directory-survey.py. Do not hand-edit — re-run it.]`", "",
           "Each address book, yearbook and members' list of the corpus: its size, the opening of its text, a sample from its "
           "middle, and the lines that name a sign or a numbering (runbook D4c). The analysis is Ezri's, in the QUEUE.", ""]
    for title, files, pick in TITLES:
        files = [f for f in files if os.path.exists(f)]
        doc += [f"## {title}", "", f"{len(files)} file(s).", ""]
        tot = 0
        for f in files:
            name = os.path.basename(f)[:-4]
            if pick is not None and name not in pick:
                raw = open(f, encoding="utf-8", errors="replace").readlines()
                n = len(body(raw)); tot += n
                doc.append(f"- `{os.path.relpath(f, G)}`: {n:,} lines (no excerpt)")
                continue
            ex, n, w = excerpt(f); tot += n
            doc += [""] + ex
        doc += ["", f"*{tot:,} lines in all.*", ""]
    with open(a.out, "x", encoding="utf-8") as fh: fh.write("\n".join(doc) + "\n")
    print(f"wrote {os.path.relpath(a.out, ROOT)}: {sum(1 for l in doc if l.startswith('### '))} excerpts")

if __name__ == "__main__":
    main()
